use warifu_core::algorithm::{Algorithm, Digits, SecretKey};
use warifu_core::google_migration::{encode_google_migration_uri, parse_google_migration_uri};
use warifu_core::totp::{generate_totp, verify_totp};
use warifu_core::uri::{parse_otpauth_uri, ParsedToken, TokenType};
use warifu_core::vault::VaultDatabase;
use proptest::prelude::*;

proptest! {
    #![proptest_config(ProptestConfig::with_cases(500))]

    /// Invariant: `parse_otpauth_uri` must NEVER panic on any arbitrary input string.
    #[test]
    fn prop_fuzz_uri_parser_never_panics(arbitrary_input in "\\PC*") {
        let _ = parse_otpauth_uri(&arbitrary_input);
    }

    /// Invariant: `parse_google_migration_uri` must NEVER panic on any arbitrary input string.
    #[test]
    fn prop_fuzz_google_migration_never_panics(arbitrary_input in "\\PC*") {
        let _ = parse_google_migration_uri(&arbitrary_input);
    }

    /// Invariant: `VaultDatabase::deserialize` must NEVER panic on any arbitrary byte stream.
    #[test]
    fn prop_fuzz_vault_deserialize_never_panics(arbitrary_bytes in prop::collection::vec(any::<u8>(), 0..4096)) {
        let _ = VaultDatabase::deserialize(&arbitrary_bytes);
    }

    /// Invariant: Any code generated by TOTP must verify successfully in constant time.
    #[test]
    fn prop_totp_code_verification_invariant(
        secret_bytes in prop::collection::vec(any::<u8>(), 10..64),
        timestamp in any::<u64>(),
        period in 1u64..120u64,
        digit_count in prop::sample::select(vec![6u32, 7u32, 8u32]),
        algo_idx in 0..3
    ) {
        let secret = SecretKey::new(secret_bytes);
        let digits = Digits::try_from(digit_count).unwrap();
        let algorithm = match algo_idx {
            1 => Algorithm::Sha256,
            2 => Algorithm::Sha512,
            _ => Algorithm::Sha1,
        };

        let code = generate_totp(&secret, timestamp, period, digits, algorithm);
        assert_eq!(code.len(), digit_count as usize);

        let is_valid = verify_totp(&secret, &code, timestamp, 0, period, digits, algorithm);
        prop_assert!(is_valid, "Valid generated TOTP code failed verification");
    }

    /// Invariant: Google migration encode and decode must be perfectly reversible.
    #[test]
    fn prop_google_migration_roundtrip_invariant(
        issuer in "[a-zA-Z0-9_]{1,30}",
        account in "[a-zA-Z0-9_@.]{1,40}",
        secret_bytes in prop::collection::vec(any::<u8>(), 10..32),
        counter in any::<u64>()
    ) {
        let original_tokens = vec![
            ParsedToken {
                token_type: TokenType::Totp,
                issuer: Some(issuer.clone()),
                account_name: account.clone(),
                secret: SecretKey::new(secret_bytes),
                algorithm: Algorithm::Sha1,
                digits: Digits::Six,
                period: 30,
                counter,
            }
        ];

        let encoded_uri = encode_google_migration_uri(&original_tokens);
        let decoded_tokens = parse_google_migration_uri(&encoded_uri)
            .expect("Valid migration URI failed decoding");

        prop_assert_eq!(decoded_tokens.len(), 1);
        prop_assert_eq!(&decoded_tokens[0].issuer, &Some(issuer));
        prop_assert_eq!(&decoded_tokens[0].account_name, &account);
        prop_assert_eq!(&decoded_tokens[0].token_type, &TokenType::Totp);
        prop_assert_eq!(&decoded_tokens[0].digits, &Digits::Six);
    }
}
